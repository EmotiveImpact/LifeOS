import { readFileSync, writeFileSync, cpSync, mkdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { join, resolve } from 'node:path';

import { matchCompositions, paper, photography, spotlights } from './v24/screen-designs.mjs';

const review = fileURLToPath(new URL('.', import.meta.url));
const { rows, originalChapters } = JSON.parse(readFileSync(join(review, 'v23-screen-accounting.json'), 'utf8'));
const keys = new Set(rows.map(row => row.key));
if (keys.size !== rows.length || !['today', 'plan', 'you', 'talk'].every(key => keys.has(key))) {
  throw new Error('The board requires a unique catalogue and all four primary screens.');
}
const layouts = matchCompositions(keys);
for (const design of [paper, photography, spotlights]) {
  for (const key of Object.keys(design)) {
    if (!layouts.has(key)) throw new Error('Unknown V24 treatment: ' + key);
  }
}
const catalogue = rows.map(({ key, title, chapter, route, opensAs }) => ({
  key, title, chapter, route, opensAs, layout: layouts.get(key)
}));
const source = readFileSync(join(review, '../apps/mobile/src/design/iconPaths.ts'), 'utf8').split('} as const;')[0];
const icons = Object.fromEntries([...source.matchAll(/^  (\w+): '([^']+)',/gm)].map(([, name, path]) => [name, path]));
const data = { chapters: originalChapters, catalogue, icons, paper, photography, spotlights };
writeFileSync(join(review, 'v24/catalogue.js'), '// Generated by review/build-visual-board-v24.mjs\nwindow.LIFE_BOARD = ' + JSON.stringify(data) + ';\n');

// Build the complete, interactive board from the original V23 document.
if (process.argv[2]) {
  const out = resolve(process.argv[2]);
  mkdirSync(out, { recursive: true });
  // Keep the legacy scripts verbatim in separate assets for static hosting.
  const archive = readFileSync(join(review, 'life-complete-board-v23.html'), 'utf8');
  let count = 0;
  const shell = archive.replace(/<script>([\s\S]*?)<\/script>/g, (_, script) => {
    const name = 'v23-archive-' + (++count) + '.js';
    writeFileSync(join(out, name), script);
    return '<script src="' + name + '"></script>';
  });
  if (count !== 2) throw new Error('Unexpected V23 archive structure');
  const legacy = shell.replace(/^<meta charset="utf-8">/, '<!doctype html><html lang="en-GB" data-theme="dark"><meta charset="utf-8">')
    .replace(/<title>[^<]*<\/title>/, '<title>LifeOS · Complete design board V24</title>')
    .replace('<div class="wrap">', '<div class="wrap" inert>');
  const ui = readFileSync(join(review, 'life-complete-board-v24.html'), 'utf8');
  writeFileSync(join(out, 'index.html'), legacy + '\n' + ui);
  cpSync(join(review, 'v24'), join(out, 'v24'), { recursive: true });
}
