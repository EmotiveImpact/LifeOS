/**
 * Life's public pages and the in-app legal text, from one source (Phase 31).
 *
 * The privacy policy, terms and support page are written once, as Markdown in `docs/launch/`. This script turns them
 * into the website's pages (`apps/site/public/*.html`) and into the text the app shows under You, Settings, About
 * (`apps/mobile/src/content/legal.ts`). Edit the Markdown, then run:
 *
 *   bun apps/site/build.ts          # write the pages and the app's text
 *   bun apps/site/build.ts --check  # fail if anything is out of date (tests/launch/site.test.ts does this too)
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const root = join(import.meta.dir, '..', '..');
const docs = join(root, 'docs', 'launch');

/** Markdown file, the page it becomes, and its name in the page's header. */
export const PAGES = [
  { source: 'privacy-policy.md', page: 'privacy.html', name: 'Privacy policy' },
  { source: 'terms.md', page: 'terms.html', name: 'Terms' },
  { source: 'support.md', page: 'support.html', name: 'Support' },
] as const;

export type LegalBlock =
  | { kind: 'heading'; text: string }
  | { kind: 'subheading'; text: string }
  | { kind: 'text'; text: string }
  | { kind: 'list'; items: string[] }
  | { kind: 'table'; head: string[]; rows: string[][] };
export type LegalDoc = { title: string; blocks: LegalBlock[] };

/**
 * Inline Markdown as the app writes copy: `**bold**` becomes `{bold}` (the words in ink), a link keeps only its words,
 * and code and emphasis marks go.
 */
export function inline(text: string): string {
  return text
    .replace(/\[([^\]]+)\]\([^)]+\)/g, '$1')
    .replace(/\*\*([^*]+)\*\*/g, '{$1}')
    .replace(/`([^`]+)`/g, '$1')
    .replace(/(^|\W)_([^_]+)_(?=\W|$)/g, '$1$2')
    .replace(/\s+/g, ' ')
    .trim();
}

const cells = (line: string) => line.trim().replace(/^\|/, '').replace(/\|$/, '').split('|').map(c => inline(c));

/** The block structure of one document: headings, paragraphs, lists and tables. That's all the legal pages use. */
export function parseDoc(markdown: string): LegalDoc {
  const lines = markdown.replace(/\r\n/g, '\n').split('\n');
  let title = '';
  const blocks: LegalBlock[] = [];
  let paragraph: string[] = [];
  let list: string[] | null = null;
  let table: string[][] | null = null;
  const flush = () => {
    if (paragraph.length) blocks.push({ kind: 'text', text: inline(paragraph.join(' ')) });
    if (list) blocks.push({ kind: 'list', items: list.map(inline) });
    if (table) {
      const [head, ...rows] = table;
      blocks.push({ kind: 'table', head, rows });
    }
    paragraph = []; list = null; table = null;
  };
  for (const raw of lines) {
    const line = raw.trimEnd();
    if (!line.trim()) { flush(); continue; }
    const heading = /^(#{1,3}) (.*)$/.exec(line);
    if (heading) {
      flush();
      const text = inline(heading[2]);
      if (heading[1] === '#') title = text;
      else blocks.push({ kind: heading[1] === '##' ? 'heading' : 'subheading', text });
      continue;
    }
    if (line.trimStart().startsWith('|')) {
      if (paragraph.length || list) flush();
      if (/^\s*\|[\s:|-]+\|\s*$/.test(line)) continue; // the row under the header
      (table ??= []).push(cells(line));
      continue;
    }
    const item = /^\s*(?:[-*]|\d+\.) (.*)$/.exec(line);
    if (item) {
      if (paragraph.length || table) flush();
      (list ??= []).push(item[1]);
      continue;
    }
    if (list && /^\s{2,}\S/.test(raw)) { list[list.length - 1] += ` ${line.trim()}`; continue; }
    if (list || table) flush();
    paragraph.push(line.replace(/^>\s?/, ''));
  }
  flush();
  return { title, blocks };
}

const read = (name: string) => readFileSync(join(docs, name), 'utf8');

/** `apps/mobile/src/content/legal.ts`: the terms and the privacy policy, as blocks the About screen renders. */
export function appModule(): string {
  const doc = (name: string) => JSON.stringify(parseDoc(read(name)), null, 2);
  return `/**
 * The terms and the privacy policy, as the app shows them under You, Settings, About.
 * Generated by apps/site/build.ts from docs/launch/terms.md and docs/launch/privacy-policy.md. Don't edit this file:
 * edit the Markdown and run \`bun apps/site/build.ts\`. A test fails if the two drift apart.
 */
export type LegalBlock =
  | { kind: 'heading'; text: string }
  | { kind: 'subheading'; text: string }
  | { kind: 'text'; text: string }
  | { kind: 'list'; items: string[] }
  | { kind: 'table'; head: string[]; rows: string[][] };
export type LegalDoc = { title: string; blocks: LegalBlock[] };

export const terms: LegalDoc = ${doc('terms.md')};

export const privacyPolicy: LegalDoc = ${doc('privacy-policy.md')};
`;
}

const escape = (s: string) => s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
const linkFor = Object.fromEntries(PAGES.map(p => [p.source, p.page]));

/** One public page: the site's frame around the Markdown, with links between the documents pointing at their pages. */
export function sitePage(source: string): string {
  const page = PAGES.find(p => p.source === source);
  if (!page) throw new Error(`Unknown page ${source}`);
  const markdown = read(source);
  const title = parseDoc(markdown).title;
  const body = Bun.markdown.html(markdown, { gfm: true } as never)
    .replace(/href="([a-z-]+\.md)"/g, (whole, file: string) => (linkFor[file] ? `href="${linkFor[file]}"` : whole));
  const nav = PAGES.map(p => `<a href="${p.page}"${p.page === page.page ? ' aria-current="page"' : ''}>${p.name}</a>`).join('\n        ');
  return `<!doctype html>
<html lang="en-GB">
<head>
  <meta charset="utf-8">
  <meta name="viewport" content="width=device-width, initial-scale=1">
  <title>${escape(title)}</title>
  <meta name="description" content="${escape(`${page.name} for Life, the planner for your health, money and life admin.`)}">
  <link rel="stylesheet" href="site.css">
</head>
<body>
  <header class="top">
    <a class="wordmark" href="index.html" aria-label="Life">L I F E</a>
    <nav aria-label="Pages">
        ${nav}
    </nav>
  </header>
  <main class="doc">
${body.trim().split('\n').map(l => `    ${l}`).join('\n')}
  </main>
  <footer class="foot">
    <p>Life · <a href="privacy.html">Privacy</a> · <a href="terms.html">Terms</a> · <a href="support.html">Support</a> · <a href="delete.html">Delete your account</a></p>
  </footer>
</body>
</html>
`;
}

/** Every generated file, by its path from the repository root. */
export function outputs(): Record<string, string> {
  return {
    'apps/mobile/src/content/legal.ts': appModule(),
    ...Object.fromEntries(PAGES.map(p => [`apps/site/public/${p.page}`, sitePage(p.source)])),
  };
}

if (import.meta.main) {
  const check = process.argv.includes('--check');
  const stale: string[] = [];
  for (const [path, text] of Object.entries(outputs())) {
    const full = join(root, path);
    let current = '';
    try { current = readFileSync(full, 'utf8'); } catch { /* new file */ }
    if (current === text) continue;
    if (check) stale.push(path);
    else { writeFileSync(full, text); console.log(`wrote ${path}`); }
  }
  if (check && stale.length) {
    console.error(`Out of date, run \`bun apps/site/build.ts\`: ${stale.join(', ')}`);
    process.exit(1);
  }
}
